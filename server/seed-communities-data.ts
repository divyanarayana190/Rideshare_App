export type SeedCommunityDef = {
  name: string;
  description: string;
  category: CommunityCategory;
  visibility: CommunityVisibility;
  verificationType: CommunityVerificationType;
  verificationDomain?: string;
  metadata: CommunityMetadata;
  logoUrl: string;
  bannerUrl: string;
  rideKeywords: string[];
  targetMembers: number;
  moderatorCount: number;
};

const RULES = [
  "Respect everyone in the community",
  "No spam or self-promotion",
  "No fake or misleading rides",
  "Share accurate pickup and dropoff details",
  "Report unsafe behavior immediately",
  "No harassment or discrimination",
  "Follow YOO community guidelines",
];

export const SEED_COMMUNITY_RULES = RULES;

function def(
  partial: Omit<SeedCommunityDef, "logoUrl" | "bannerUrl"> & {
    logoUrl?: string;
    bannerUrl?: string;
  },
): SeedCommunityDef {
  const slug = slugifyCommunityName(partial.name);
  const initials = partial.name.split(" ").slice(0, 2).map((w) => w[0]).join("");
  const color = (partial.metadata.themeColor ?? "#1E88FF").replace("#", "");
  return {
    ...partial,
    logoUrl:
      partial.logoUrl ??
      `https://ui-avatars.com/api/?name=${encodeURIComponent(initials)}&background=${color}&color=fff&size=256&bold=true`,
    bannerUrl:
      partial.bannerUrl ??
      `https://images.unsplash.com/photo-1486406146926-c627a92ad1ab?w=1200&h=400&fit=crop`,
  };
}

